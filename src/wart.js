// 등급(녹슨·강철·미스릴·룬·전설)마다 쇠 색. 이름 앞말(TIER_PRE)과 같은 순서
const METAL = [
  [0xc8b8a0, 0x9a7a62, 0x5a4434],
  [0xf4f8fc, 0xb8c0cc, 0x6a7280],
  [0xe0faff, 0x6fc8ff, 0x2a6ab0],
  [0xffe0ff, 0xd090ff, 0x6a3aa0],
  [0xfff2b0, 0xffa030, 0xc04010],
];
const BASE = { o: 0x0a0710, w: 0xc8884a, W: 0x7a4a20, k: 0x5a3626, g: 0xffd75e, a: 0xe8343a, s: 0xe8e2d0 };

// 무기 그림 텍스처 'w_<종류><등급>'을 만든다(Boot에서 한 번)
export function makeWeaponTextures(g) {
  for (const [id, rows] of Object.entries(WART)) METAL.forEach(([L, M, D], tier) => {
    if (g.scene.textures.exists(`w_${id}${tier}`)) return;   // PNG로 갈아 끼운 그림은 그대로 둔다
    const pal = { ...BASE, L, M, D };
    g.clear();
    rows.forEach((row, y) => [...row].forEach((ch, x) => { if (pal[ch] !== undefined) g.fillStyle(pal[ch]).fillRect(x, y, 1, 1); }));
    g.generateTexture(`w_${id}${tier}`, 16, 16);
  });
}
